export const emojiSymbols: string[] = emojiGroups.flatMap((group) =>
  group.items.map((item) => item.emoji),
)
export function normalizeEmojiSearch(value: string) {
  return value
    .toLocaleLowerCase('es')
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .trim()
}
// One emoji sequence: supports flags, keycaps, skin tones and joined family/profession emoji.
// Plain text, HTML and multiple unrelated emoji are rejected.
export function isEmojiSymbol(value: unknown): value is string {
  return (
    typeof value === 'string' &&
    value.length <= 64 &&
    /^(?:\p{Regional_Indicator}{2}|[#*0-9]\uFE0F?\u20E3|\p{Extended_Pictographic}[\uFE0E\uFE0F]?\p{Emoji_Modifier}?(?:[\u{E0020}-\u{E007E}]+\u{E007F})?(?:\u200D\p{Extended_Pictographic}[\uFE0E\uFE0F]?\p{Emoji_Modifier}?)*)$/u.test(
      value,
    )
  )
}
